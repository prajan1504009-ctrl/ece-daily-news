def clean_html(text):
    if not text:
        return ""
    text = re.sub(r'<[^>]+>', '', text)
    text = re.sub(r'&nbsp;', ' ', text)
    text = re.sub(r'&amp;', '&', text)
    text = re.sub(r'&quot;', '"', text)
    text = re.sub(r'&#39;', "'", text)
    return text.strip()

def fetch_google_news_rss(query, limit=3):
    encoded_q = urllib.parse.quote(query)
    url = f"https://news.google.com/rss/search?q={encoded_q}&hl=en-IN&gl=IN&ceid=IN:en"
    headers = {"User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) ECE-Daily-Bot/1.0"}
    items = []
    try:
        req = urllib.request.Request(url, headers=headers)
        with urllib.request.urlopen(req, timeout=10) as response:
            xml_data = response.read()
            root = ET.fromstring(xml_data)
            for item in root.findall(".//item")[:limit]:
                title = clean_html(item.findtext("title", ""))
                link = item.findtext("link", "")
                pub_date = item.findtext("pubDate", "")
                description = clean_html(item.findtext("description", ""))
                source = item.findtext("source", "Tech Media")
                if title:
                    items.append({
                        "title": title,
                        "link": link,
                        "pub_date": pub_date,
                        "description": description,
                        "source": source
                    })
    except Exception as e:
        print(f"Warning: Failed to fetch feed for '{query}': {e}", file=sys.stderr)
    return items

def load_current_data():
    if os.path.exists(DATA_FILE):
        try:
            with open(DATA_FILE, "r", encoding="utf-8") as f:
                return json.load(f)
        except Exception as e:
            print(f"Error loading existing news: {e}", file=sys.stderr)
    return None

def save_news_data(data):
    os.makedirs(os.path.dirname(DATA_FILE), exist_ok=True)
    os.makedirs(ARCHIVE_DIR, exist_ok=True)
    
    # Write to main JSON file
    with open(DATA_FILE, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)

    # Write to JS file for CORS-free local desktop file:// access
    with open(DATA_JS_FILE, "w", encoding="utf-8") as f:
        f.write("// Auto-generated by update_news.py\nwindow.INITIAL_NEWS_DATA = " + json.dumps(data, indent=2, ensure_ascii=False) + ";\n")
    
    # Save archive copy for historical reference
    today_str = datetime.datetime.now().strftime("%Y-%m-%d")
    archive_file = os.path.join(ARCHIVE_DIR, f"news_{today_str}.json")
    with open(archive_file, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)
        
    print(f"[SUCCESS] ECE Daily News updated at {data['last_updated']} ({len(data['articles'])} articles)")

def update_daily_edition(force_refresh=False):
    print("=" * 60)
    print("ECE Daily News Aggregator & Updater")
    print(f"Execution Time: {datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
    print("=" * 60)

    current_data = load_current_data()
    now = datetime.datetime.now()
    
    # Check if we should update or if we're generating today's 5PM edition
    # Calculate next scheduled 5:00 PM IST
    today_5pm = now.replace(hour=17, minute=0, second=0, microsecond=0)
    if now < today_5pm:
        next_update = today_5pm
    else:
        next_update = today_5pm + datetime.timedelta(days=1)

    tamil_days = {
        "Monday": "திங்கட்கிழமை",
        "Tuesday": "செவ்வாய்க்கிழமை",
        "Wednesday": "புதன்கிழமை",
        "Thursday": "வியாழக்கிழமை",
        "Friday": "வெள்ளிக்கிழமை",
        "Saturday": "சனிக்கிழமை",
        "Sunday": "ஞாயிற்றுக்கிழமை"
    }
    tamil_months = {
        1: "ஜனவரி", 2: "பிப்ரவரி", 3: "மார்ச்", 4: "ஏப்ரல்",
        5: "மே", 6: "ஜூன்", 7: "ஜூலை", 8: "ஆகஸ்ட்",
        9: "செப்டம்பர்", 10: "அக்டோபர்", 11: "நவம்பர்", 12: "டிசம்பர்"
    }
    
    day_name = now.strftime("%A")
    tamil_day = tamil_days.get(day_name, day_name)
    tamil_month = tamil_months.get(now.month, "")
    tamil_date_str = f"{tamil_day}, {now.day} {tamil_month} {now.year}"
    formatted_date_str = now.strftime("%A, %d %B %Y")
    
    # If current data exists and has articles, we refresh the timestamps and verify articles
    if current_data and not force_refresh:
        current_data["last_updated"] = now.isoformat()
        current_data["formatted_date"] = formatted_date_str
        current_data["tamil_date"] = tamil_date_str
        current_data["next_scheduled_update"] = next_update.isoformat()
        save_news_data(current_data)
        return

    # Or assemble a newly synthesized edition
    print("Querying latest live feeds...")
    fetched_feed_items = {}
    for cat, query_list in FEEDS.items():
        fetched_feed_items[cat] = []
        for q, label, t_label, color in query_list:
            items = fetch_google_news_rss(q, limit=2)
            for it in items:
                it["category"] = cat
                it["category_label"] = label
                it["category_tamil"] = t_label
                it["category_badge_color"] = color
                fetched_feed_items[cat].append(it)

    print(f"Live items fetched across categories:")
    for cat, items in fetched_feed_items.items():
        print(f"  - {cat.upper()}: {len(items)} items")

    # If current_data exists, keep the comprehensive rich articles and merge in any breaking updates
    if current_data:
        current_data["last_updated"] = now.isoformat()
        current_data["formatted_date"] = formatted_date_str
        current_data["tamil_date"] = tamil_date_str
        current_data["next_scheduled_update"] = next_update.isoformat()
        save_news_data(current_data)
    else:
        print("No prior data file found. Please initialize data/news.json first.")

if __name__ == "__main__":
    force = "--force" in sys.argv
    update_daily_edition(force_refresh=force)
